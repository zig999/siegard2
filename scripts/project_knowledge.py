#!/usr/bin/env python3
"""Generate the derived artifacts of a knowledge base, or verify the committed ones.

Four outputs, and R50 closes the list of projections at three: `index.md`, a glossary from
`definition` objects, and a context map from `boundary.context_relationships`. A fourth
requires a fixture that demands it. `graph.json` is the materialized graph rather than a
projection, and R42 names it and `index.md` together as derived and never hand-edited.

Every output is reproducible from the graph and none is a normative source (R51). Ordering
is lexicographic by id throughout, which is what makes "identical input produces
byte-identical output" true of a generated file rather than merely intended.

Two modes, and the separation is the same one CLAUDE.md draws between `dist` and
`dist-check`: writing regenerates, `--check` verifies and mutates nothing. A check that
repairs what it was meant to detect reports success on a defect.

Declared dependencies: PyYAML, jsonschema.

Usage:  scripts/project_knowledge.py <knowledge_root> [--check]
        with no root, every fixtures/*/knowledge tree is processed
Exit:   0 written, or committed output matches; 1 output differs under --check;
        2 cannot run
"""

from __future__ import annotations

import json
import sys
from dataclasses import asdict
from pathlib import Path

from frontmatter_lib import REPO_ROOT, display

from cli import cannot_run
from derived_artifacts import DERIVED_NAMES

try:
    import yaml  # noqa: F401
except ImportError:
    cannot_run("cannot run: PyYAML is not installed (pip install pyyaml)")

try:
    from jsonschema import Draft202012Validator
except ImportError:
    cannot_run("cannot run: jsonschema is not installed (pip install jsonschema)")

from knowledge_graph_lib import (  # noqa: E402
    EDGE_KINDS,
    GRAPH_CONTRACT,
    Graph,
    context_of,
    load,
)

GRAPH_SCHEMA_PATH = REPO_ROOT / "schemas" / "knowledge-graph.v1.json"

KO_TYPES = ("boundary", "definition", "rule", "lifecycle", "interface", "process")

BANNER = (
    "<!-- Generated by scripts/project_knowledge.py from the knowledge base. Never "
    "hand-edited: R42 and R51 make this a projection, reproducible from the graph and "
    "normative nowhere. -->"
)


def materialize(graph: Graph) -> dict:
    """The graph as data, ordered so two runs over one knowledge base agree byte for byte."""
    nodes = []
    for node in sorted(graph.nodes.values(), key=lambda n: n.id):
        entry = {
            "id": node.id,
            "kind": node.kind,
            "title": node.data["title"],
            "status": node.data["status"],
        }
        if node.is_ko:
            entry["question"] = node.data["question"]
            if "boundary" in node.data:
                entry["boundary"] = node.data["boundary"]
            context = context_of(graph, node.id)
            if context is not None and context != node.id:
                entry["context"] = context
            if "ddd" in node.data:
                entry["ddd"] = node.data["ddd"]
        nodes.append(entry)

    edge_kinds = {}
    for name, kind in EDGE_KINDS.items():
        row = asdict(kind)
        row.pop("name")
        row["origin_types"] = list(kind.origin_types)
        row["target_types"] = list(kind.target_types)
        edge_kinds[name] = row

    return {
        "contract_version": GRAPH_CONTRACT,
        "edge_kinds": edge_kinds,
        "nodes": nodes,
        "edges": [
            {"source": e.source, "target": e.target, "kind": e.kind, "locator": e.locator}
            for e in graph.edges
        ],
    }


def render_index(graph: Graph, materialized: dict) -> str:
    """The progressive-disclosure entry: counts first, then the retrieval key of every object."""
    lines = [BANNER, "", "# Knowledge base index", "", "## Nodes by type", "", "| type | count |", "|---|---|"]
    counts = {kind: 0 for kind in KO_TYPES}
    counts["adr"] = 0
    for node in materialized["nodes"]:
        counts[node["kind"]] = counts.get(node["kind"], 0) + 1
    for kind in (*KO_TYPES, "adr"):
        lines.append(f"| `{kind}` | {counts[kind]} |")
    lines += ["", "## Bounded contexts", ""]

    contexts = sorted(
        node["id"]
        for node in materialized["nodes"]
        if node["kind"] == "boundary" and node.get("ddd") == "bounded-context"
    )
    for context in contexts:
        node = graph.nodes[context]
        lines.append(f"### {node.data['title']} — `{context}`")
        lines.append("")
        lines.append(f"{node.data['description']}")
        lines.append("")
        lines.append("| id | type | question |")
        lines.append("|---|---|---|")
        members = [
            entry
            for entry in materialized["nodes"]
            if entry.get("context") == context or entry["id"] == context
        ]
        for entry in sorted(members, key=lambda e: e["id"]):
            question = entry.get("question", "")
            lines.append(f"| `{entry['id']}` | `{entry['kind']}` | {question} |")
        lines.append("")

    decisions = [n for n in materialized["nodes"] if n["kind"] == "adr"]
    lines += ["## Decisions", ""]
    if decisions:
        lines += ["| id | title | status |", "|---|---|---|"]
        for entry in decisions:
            lines.append(f"| `{entry['id']}` | {entry['title']} | {entry['status']} |")
    else:
        lines.append("None.")
    lines.append("")
    return "\n".join(lines)


def render_glossary(graph: Graph, materialized: dict) -> str:
    """The ubiquitous language, which R4 forbids recording as an artifact of its own.

    Derived from the `definition` objects and their `aliases`, so the one authoritative
    surface form stays in the knowledge object and this file stays a view of it.
    """
    lines = [BANNER, "", "# Glossary", "", "Derived from every `definition` in the knowledge base.", ""]
    lines += ["| term | aliases | id | meaning |", "|---|---|---|---|"]
    for entry in materialized["nodes"]:
        if entry["kind"] != "definition":
            continue
        node = graph.nodes[entry["id"]]
        aliases = ", ".join(f"`{a}`" for a in sorted(node.data.get("aliases") or [])) or "—"
        lines.append(
            f"| {node.data['title']} | {aliases} | `{entry['id']}` | {node.data['description']} |"
        )
    lines.append("")
    return "\n".join(lines)


def render_context_map(graph: Graph, materialized: dict) -> str:
    """The context map, derived from `context_relationships` and never authored twice.

    A diagram is a projection, per R47, so it may appear here and may not be the only place
    a relationship exists. The table is the readable form of the same edges.
    """
    contexts = sorted(
        node["id"]
        for node in materialized["nodes"]
        if node["kind"] == "boundary" and node.get("ddd") == "bounded-context"
    )
    lines = [BANNER, "", "# Context map", "", "| from | pattern | to |", "|---|---|---|"]
    relationships = sorted(
        (e.source, graph.nodes[e.source], e.target)
        for e in graph.edges
        if e.kind == "context_relationships[].with"
    )
    rows = []
    for source_id, node, target_id in relationships:
        for relationship in node.data.get("context_relationships") or []:
            if relationship["with"] == target_id:
                rows.append((source_id, relationship["pattern"], target_id))
    for source_id, pattern, target_id in sorted(set(rows)):
        lines.append(f"| `{source_id}` | {pattern} | `{target_id}` |")
    if not rows:
        lines.append("| — | — | — |")
    lines += ["", "## Diagram", "", "```mermaid", "graph LR"]
    for context in contexts:
        lines.append(f"  {_mermaid_id(context)}[{graph.nodes[context].data['title']}]")
    for source_id, pattern, target_id in sorted(set(rows)):
        lines.append(f"  {_mermaid_id(source_id)} -->|{pattern}| {_mermaid_id(target_id)}")
    lines += ["```", ""]
    return "\n".join(lines)


def _mermaid_id(node_id: str) -> str:
    return node_id.replace(".", "_")


def outputs(graph: Graph) -> dict[str, str]:
    """Every derived file, keyed by name relative to the knowledge root.

    The names are asserted against `derived_artifacts.DERIVED_NAMES`, which is the one place they
    live. `src/claude/hooks/reject-derived-write.py` refuses writes to that set, and a second copy
    of the list would drift in the worst direction: a hook protecting a file this no longer
    produces, and not protecting one it does.
    """
    materialized = materialize(graph)
    Draft202012Validator(json.loads(GRAPH_SCHEMA_PATH.read_text())).validate(materialized)
    produced = {
        "graph.json": json.dumps(materialized, indent=2, sort_keys=False, ensure_ascii=False) + "\n",
        "index.md": render_index(graph, materialized),
        "glossary.md": render_glossary(graph, materialized),
        "context-map.md": render_context_map(graph, materialized),
    }
    if set(produced) != DERIVED_NAMES:
        raise AssertionError(
            f"the projections written here are {sorted(produced)} and derived_artifacts declares "
            f"{sorted(DERIVED_NAMES)}; the hook and the materializer must agree"
        )
    return produced


def run(root: Path, check: bool) -> tuple[int, list[str]]:
    graph = load(root)
    if graph.problems:
        return 1, [
            f"{display(root)}: cannot project a knowledge base that does not validate "
            f"({len(graph.problems)} problem(s)) — run scripts/validate_knowledge.py"
        ]
    generated = outputs(graph)
    differences: list[str] = []
    for name, content in generated.items():
        path = root / name
        if check:
            if not path.is_file():
                differences.append(f"{display(path)}: missing, and this file is generated")
            elif path.read_text() != content:
                differences.append(
                    f"{display(path)}: committed content differs from what the graph produces"
                )
        else:
            path.write_text(content)
    return (1 if differences else 0), differences


def discover() -> list[Path]:
    return sorted(p for p in (REPO_ROOT / "fixtures").glob("*/knowledge") if p.is_dir())


def main() -> int:
    check = "--check" in sys.argv
    roots = [Path(a) for a in sys.argv[1:] if a != "--check"] or discover()
    if not roots:
        cannot_run("cannot run: no knowledge base given and no fixtures/*/knowledge tree exists")
    if not GRAPH_SCHEMA_PATH.is_file():
        cannot_run(f"cannot run: schema {GRAPH_SCHEMA_PATH} does not exist")

    status = 0
    problems: list[str] = []
    for root in roots:
        if not root.is_dir():
            cannot_run(f"cannot run: knowledge root {root} does not exist")
        code, differences = run(root, check)
        status |= code
        problems.extend(differences)
        verb = "checked" if check else "wrote"
        print(f"projections {verb} for {display(root)}")

    if problems:
        print(f"FAILED: {len(problems)} problem(s)\n")
        for problem in problems:
            print(f"  {problem}")
        return 1
    print("projections match the graph" if check else "projections regenerated")
    return status


if __name__ == "__main__":
    raise SystemExit(main())
