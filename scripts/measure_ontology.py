#!/usr/bin/env python3
"""Measure type utilization and edge traversal utility, as R52 requires.

R52 states the removal criterion: a type holding under 5% of nodes with no check branching
on it, or an edge no resolution reads, MUST be removed rather than retained for symmetry.
A criterion nobody measures removes nothing, so this script produces the figures and
records them.

It reports and never decides. Removing a type or an edge changes the closed vocabularies of
R5 and R17, which is a specification change and a maintainer's call. Nor is any figure here
a gate: spec 0002 R8 and spec 0001 R25 both forbid expressing an acceptance criterion as a
coverage figure, and the same reasoning holds for this one.

"A check branching on it" is answered from two mechanical signals rather than from an
opinion: whether schemas/knowledge-object.v1.json carries a conditional branch on the type,
and whether the edge table names the type as an origin or a target. Both are read from the
artifacts, so the answer moves when they move.

Declared dependencies: PyYAML, jsonschema.

Usage:  scripts/measure_ontology.py <knowledge_root> [--check]
        with no root, every fixtures/*/knowledge tree is measured
Exit:   0 recorded, or the record matches; 1 the record is stale under --check; 2 cannot run
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

from frontmatter_lib import REPO_ROOT, display

try:
    import yaml  # noqa: F401
except ImportError:
    sys.exit("cannot run: PyYAML is not installed (pip install pyyaml)")

try:
    from jsonschema import Draft202012Validator  # noqa: F401
except ImportError:
    sys.exit("cannot run: jsonschema is not installed (pip install jsonschema)")

from knowledge_graph_lib import EDGE_KINDS, KO_SCHEMA_PATH, Graph, load  # noqa: E402

KO_TYPES = ("definition", "rule", "lifecycle", "interface", "boundary", "process")
THRESHOLD = 0.05
RECORD_NAME = "ontology-utilization.md"

BANNER = (
    "<!-- Generated by scripts/measure_ontology.py. The R52 measurement, recorded because a "
    "threshold nobody measures removes nothing. Reports; decides nothing. -->"
)


def schema_branches() -> set[str]:
    """Which types the frontmatter contract carries a conditional branch on."""
    schema = json.loads(KO_SCHEMA_PATH.read_text())
    found = set()
    for clause in schema.get("allOf", []):
        condition = clause.get("if", {}).get("properties", {}).get("type", {})
        if "const" in condition:
            found.add(condition["const"])
    return found


def edge_branches() -> dict[str, set[str]]:
    """Which types the edge table names, as an origin or as a target."""
    origins: dict[str, set[str]] = {}
    for name, kind in EDGE_KINDS.items():
        for kind_type in kind.origin_types:
            origins.setdefault(kind_type, set()).add(f"{name} (origin)")
        for kind_type in kind.target_types:
            origins.setdefault(kind_type, set()).add(f"{name} (target)")
    return origins


def render(graph: Graph) -> str:
    nodes = [n for n in graph.nodes.values() if n.is_ko]
    total = len(nodes)
    counts = Counter(n.kind for n in nodes)
    edge_counts = Counter(e.kind for e in graph.edges)
    branches = schema_branches()
    named_by_edges = edge_branches()

    lines = [
        BANNER,
        "",
        "# Ontology utilization",
        "",
        f"Measured over `{display(graph.root)}`: {total} knowledge objects, "
        f"{len(graph.edges)} edges.",
        "",
        "## Type utilization",
        "",
        "R52 removes a type holding under 5% of nodes **and** having no check branch on it.",
        "Both conditions must hold, so a rare type a check reads is retained.",
        "",
        "| type | nodes | share | schema branch | named by edges | R52 removal candidate |",
        "|---|---|---|---|---|---|",
    ]
    candidates: list[str] = []
    for kind in KO_TYPES:
        count = counts.get(kind, 0)
        share = (count / total) if total else 0.0
        has_branch = kind in branches
        edge_named = len(named_by_edges.get(kind, ()))
        candidate = share < THRESHOLD and not has_branch and edge_named == 0
        if candidate:
            candidates.append(kind)
        lines.append(
            f"| `{kind}` | {count} | {share:.1%} | {'yes' if has_branch else 'no'} | "
            f"{edge_named} | {'YES' if candidate else 'no'} |"
        )

    lines += [
        "",
        "## Edge traversal utility",
        "",
        "R52 removes an edge no resolution reads. An edge the table marks as not traversed is",
        "read by no expansion by construction, which is the condition rather than evidence",
        "against it.",
        "",
        "| edge | instances | traversed | depth | R52 removal candidate |",
        "|---|---|---|---|---|",
    ]
    edge_candidates: list[str] = []
    for name, kind in EDGE_KINDS.items():
        count = edge_counts.get(name, 0)
        candidate = not kind.traversed or count == 0
        if candidate:
            edge_candidates.append(name)
        lines.append(
            f"| `{name}` | {count} | {'yes' if kind.traversed else 'no'} | "
            f"{kind.depth if kind.depth is not None else '—'} | {'YES' if candidate else 'no'} |"
        )

    lines += ["", "## What the measurement found", ""]
    if candidates:
        lines.append(f"Types meeting both removal conditions: {', '.join(f'`{c}`' for c in candidates)}.")
    else:
        lines.append("No type meets both removal conditions of R52.")
    if edge_candidates:
        lines.append("")
        lines.append(
            f"Edges meeting the removal condition: {', '.join(f'`{c}`' for c in edge_candidates)}."
        )
        lines.append("")
        lines.append(
            "Each is an edge no expansion reads. Removing one narrows the closed vocabulary of "
            "R17, which is a specification change and a maintainer's decision, so this record "
            "names the candidates and stops there."
        )
    else:
        lines.append("")
        lines.append("Every declared edge is traversed and has at least one instance.")
    lines.append("")
    lines.append(
        f"`superseded_by` is counted apart: {len(graph.supersessions)} reference(s). It is not an "
        "edge, its target MUST resolve under R22, and expansion MUST NOT follow it, so R52's "
        "traversal criterion does not apply to it. It is reported here so moving it out of the "
        "edge table did not also move it out of view."
    )
    lines.append("")
    lines.append(
        "One measurement over one fixture calibrates nothing on its own. The specification "
        "defers the body length ceiling of R48 and the expansion depth of the traversal table "
        "to this measurement, and neither should move until more than one knowledge base has "
        "been measured."
    )
    lines.append("")
    return "\n".join(lines)


def run(root: Path, check: bool) -> tuple[int, list[str]]:
    graph = load(root)
    if graph.problems:
        return 1, [
            f"{display(root)}: cannot measure a knowledge base that does not validate "
            f"({len(graph.problems)} problem(s)) — run scripts/validate_knowledge.py"
        ]
    content = render(graph)
    record = root.parent / RECORD_NAME
    if check:
        if not record.is_file():
            return 1, [f"{display(record)}: missing, and this record is generated"]
        if record.read_text() != content:
            return 1, [f"{display(record)}: recorded measurement is stale"]
        return 0, []
    record.write_text(content)
    return 0, []


def discover() -> list[Path]:
    return sorted(p for p in (REPO_ROOT / "fixtures").glob("*/knowledge") if p.is_dir())


def main() -> int:
    check = "--check" in sys.argv
    roots = [Path(a) for a in sys.argv[1:] if a != "--check"] or discover()
    if not roots:
        sys.exit("cannot run: no knowledge base given and no fixtures/*/knowledge tree exists")

    problems: list[str] = []
    for root in roots:
        if not root.is_dir():
            sys.exit(f"cannot run: knowledge root {root} does not exist")
        _code, found = run(root, check)
        problems.extend(found)
        print(f"ontology measured for {display(root)}")

    if problems:
        print(f"FAILED: {len(problems)} problem(s)\n")
        for problem in problems:
            print(f"  {problem}")
        return 1
    print("measurement matches the record" if check else "measurement recorded")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
